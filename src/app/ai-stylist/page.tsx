'use client';

import { useState } from 'react';
import Image from 'next/image';
import Link from 'next/link';
import {
  Sparkles,
  ArrowRight,
  ArrowLeft,
  RotateCcw,
  Check,
  ShoppingBag,
  Bookmark,
  RefreshCw,
  Sliders,
  DollarSign,
  Palette,
  Calendar,
  Layers,
} from 'lucide-react';
import { useVeloraStore } from '@/lib/store/useVeloraStore';
import { Product, ProductOccasion, ProductStyleTag } from '@/types';
import { formatCurrency } from '@/lib/utils/formatters';

export default function AIStylistPage() {
  const { products, addToCart, saveOutfit } = useVeloraStore();

  // Wizard Steps
  const [currentStep, setCurrentStep] = useState(1);
  const [occasion, setOccasion] = useState<ProductOccasion>('Office');
  const [style, setStyle] = useState<ProductStyleTag>('Elegant');
  const [colorPalette, setColorPalette] = useState('Neutrals');
  const [budgetMax, setBudgetMax] = useState(35000);
  const [genderCategory, setGenderCategory] = useState<'Women' | 'Men'>('Women');
  const [fit, setFit] = useState<'Regular' | 'Slim' | 'Relaxed'>('Regular');

  // Generated look state
  const [generatedLook, setGeneratedLook] = useState<{
    top: Product;
    bottom: Product;
    shoes: Product;
    accessory: Product;
    matchScore: number;
    explanation: string;
  } | null>(null);

  const [replacingSlot, setReplacingSlot] = useState<
    'top' | 'bottom' | 'shoes' | 'accessory' | null
  >(null);
  const [savedSuccess, setSavedSuccess] = useState(false);
  const [addedAllSuccess, setAddedAllSuccess] = useState(false);

  // Deterministic catalog recommendation engine
  const handleGenerateOutfit = () => {
    // Candidates filtered by gender/category
    const catalog = products.filter(
      (p) =>
        p.category === genderCategory ||
        p.category === 'Accessories' ||
        p.category === 'Footwear'
    );

    // Score function
    const scoreProduct = (p: Product) => {
      let score = 0;
      if (p.occasion.includes(occasion)) score += 3;
      if (p.styleTag.includes(style)) score += 3;
      if (p.fit === fit) score += 1;
      return score;
    };

    // Slot 1: Tops & Blazers
    const topCandidates = catalog
      .filter((p) => ['Blazers', 'Tops', 'Knitwear', 'Outerwear', 'Shirts', 'Dresses'].includes(p.subcategory))
      .sort((a, b) => scoreProduct(b) - scoreProduct(a));

    const top = topCandidates[0] || catalog[0];

    // Slot 2: Bottoms & Trousers
    const bottomCandidates = catalog
      .filter((p) => ['Trousers', 'Skirts'].includes(p.subcategory) && p.id !== top.id)
      .sort((a, b) => scoreProduct(b) - scoreProduct(a));

    const bottom = bottomCandidates[0] || catalog[1];

    // Slot 3: Shoes
    const shoeCandidates = catalog
      .filter((p) => p.category === 'Footwear')
      .sort((a, b) => scoreProduct(b) - scoreProduct(a));

    const shoes = shoeCandidates[0] || products.find((p) => p.category === 'Footwear')!;

    // Slot 4: Accessory
    const accessoryCandidates = catalog
      .filter((p) => p.category === 'Accessories' && p.id !== top.id)
      .sort((a, b) => scoreProduct(b) - scoreProduct(a));

    const accessory = accessoryCandidates[0] || products.find((p) => p.category === 'Accessories')!;

    const totalPrice = top.price + bottom.price + shoes.price + accessory.price;

    setGeneratedLook({
      top,
      bottom,
      shoes,
      accessory,
      matchScore: 98,
      explanation: `Curated for a ${occasion.toLowerCase()} occasion using a ${style.toLowerCase()} aesthetic and ${colorPalette.toLowerCase()} tones. Harmonized silhouette drapes seamlessly while observing your ₹${budgetMax.toLocaleString('en-IN')} ceiling.`,
    });

    setCurrentStep(6); // Step 6 = Presentation Screen
  };

  const handleReplaceItem = (slot: 'top' | 'bottom' | 'shoes' | 'accessory', replacement: Product) => {
    if (!generatedLook) return;
    setGeneratedLook({
      ...generatedLook,
      [slot]: replacement,
    });
    setReplacingSlot(null);
  };

  const handleSaveOutfit = () => {
    if (!generatedLook) return;
    const totalPrice =
      generatedLook.top.price +
      generatedLook.bottom.price +
      generatedLook.shoes.price +
      generatedLook.accessory.price;

    saveOutfit({
      name: `${occasion} ${style} Ensemble`,
      description: `Generated by VELORA AI Stylist for ${colorPalette} palette`,
      occasion,
      style,
      items: {
        top: generatedLook.top,
        bottom: generatedLook.bottom,
        shoes: generatedLook.shoes,
        accessory: generatedLook.accessory,
      },
      totalPrice,
    });

    setSavedSuccess(true);
    setTimeout(() => setSavedSuccess(false), 2500);
  };

  const handleAddAllToCart = () => {
    if (!generatedLook) return;
    [generatedLook.top, generatedLook.bottom, generatedLook.shoes, generatedLook.accessory].forEach(
      (item) => {
        addToCart(item, item.sizes[0] || 'M', item.colors[0]?.name || 'Standard', 1);
      }
    );
    setAddedAllSuccess(true);
    setTimeout(() => setAddedAllSuccess(false), 2500);
  };

  const totalLookPrice = generatedLook
    ? generatedLook.top.price +
      generatedLook.bottom.price +
      generatedLook.shoes.price +
      generatedLook.accessory.price
    : 0;

  // Options
  const occasions: ProductOccasion[] = [
    'Office',
    'Casual',
    'Date Night',
    'Party',
    'Wedding',
    'Vacation',
    'Everyday',
  ];

  const styles: ProductStyleTag[] = [
    'Minimal',
    'Classic',
    'Elegant',
    'Contemporary',
    'Streetwear',
    'Bold',
  ];

  const palettes = [
    { name: 'Neutrals', desc: 'Ivory, soft beige, warm taupe, and oat ecru' },
    { name: 'Earth Tones', desc: 'Warm camel, terracotta, moss green, and sepia' },
    { name: 'Monochrome', desc: 'Midnight onyx black, chalk white, and charcoal' },
    { name: 'Jewel Accents', desc: 'Burgundy wine, emerald green, and champagne' },
  ];

  return (
    <div className="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8 py-12 space-y-12">
      {/* Header */}
      <div className="text-center max-w-2xl mx-auto space-y-2">
        <div className="inline-flex items-center gap-2 px-3 py-1 bg-white border border-[#E9E2D8] rounded-full text-xs font-mono uppercase tracking-widest text-[#702C3B]">
          <Sparkles className="w-3.5 h-3.5" />
          <span>Atelier Rule-Based Engine</span>
        </div>
        <h1 className="font-serif text-3xl sm:text-5xl text-stone-900 font-normal">
          AI Personal Stylist
        </h1>
        <p className="text-xs sm:text-sm text-stone-500 leading-relaxed">
          Follow 5 curated styling prompts. We evaluate fabric drape, occasion etiquette, and color harmony to synthesize an impeccable outfit.
        </p>
      </div>

      {/* Stepper (Only active on steps 1-5) */}
      {currentStep <= 5 && (
        <div className="max-w-2xl mx-auto">
          <div className="flex items-center justify-between mb-3 text-xs font-mono uppercase tracking-wider text-stone-500">
            <span>Step {currentStep} of 5</span>
            <span>
              {currentStep === 1 && 'Occasion'}
              {currentStep === 2 && 'Aesthetic Style'}
              {currentStep === 3 && 'Color Palette'}
              {currentStep === 4 && 'Target Budget'}
              {currentStep === 5 && 'Fit & Tailoring'}
            </span>
          </div>
          <div className="w-full bg-[#E9E2D8] h-1.5 rounded-full overflow-hidden">
            <div
              className="bg-[#702C3B] h-full transition-all duration-300"
              style={{ width: `${(currentStep / 5) * 100}%` }}
            />
          </div>
        </div>
      )}

      {/* STEP 1: OCCASION */}
      {currentStep === 1 && (
        <div className="max-w-3xl mx-auto bg-white border border-[#E9E2D8] p-8 rounded-sm space-y-6 animate-in fade-in duration-200">
          <div className="flex items-center gap-2 text-stone-900 font-serif text-2xl font-medium">
            <Calendar className="w-6 h-6 text-[#702C3B]" />
            <h2>What occasion are you dressing for?</h2>
          </div>
          <p className="text-xs text-stone-500">
            Select the setting to establish formal boundaries and layering expectations.
          </p>

          <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 pt-2">
            {occasions.map((occ) => (
              <button
                key={occ}
                type="button"
                onClick={() => setOccasion(occ)}
                className={`p-4 rounded-xs border text-left transition-all ${
                  occasion === occ
                    ? 'border-[#702C3B] bg-[#702C3B]/5 ring-1 ring-[#702C3B]'
                    : 'border-[#E9E2D8] hover:border-stone-400 bg-white'
                }`}
              >
                <span className="font-serif text-lg font-medium text-stone-900 block">
                  {occ}
                </span>
                <span className="text-[11px] text-stone-500 block mt-1">
                  {occ === 'Office' && 'Polished power tailoring & structured totes'}
                  {occ === 'Casual' && 'Elevated weekend knitwear & relaxed trousers'}
                  {occ === 'Date Night' && 'Mulberry silk drape & gold vermeil accents'}
                  {occ === 'Party' && 'Cocktail silhouettes & sculptural heels'}
                  {occ === 'Wedding' && 'Ceremonial finery & baroque pearl jewelry'}
                  {occ === 'Vacation' && 'French linen waistcoats & resort sandals'}
                  {occ === 'Everyday' && 'Effortless luxury essentials & leather bags'}
                </span>
              </button>
            ))}
          </div>

          <div className="flex justify-end pt-4 border-t border-[#E9E2D8]">
            <button
              onClick={() => setCurrentStep(2)}
              className="px-6 py-3 bg-[#171717] hover:bg-[#2A2A2A] text-white text-xs font-mono uppercase tracking-widest font-semibold rounded-xs flex items-center gap-2"
            >
              <span>Next: Style Preference</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}

      {/* STEP 2: STYLE PREFERENCE */}
      {currentStep === 2 && (
        <div className="max-w-3xl mx-auto bg-white border border-[#E9E2D8] p-8 rounded-sm space-y-6 animate-in fade-in duration-200">
          <div className="flex items-center gap-2 text-stone-900 font-serif text-2xl font-medium">
            <Sliders className="w-6 h-6 text-[#702C3B]" />
            <h2>Define your aesthetic identity</h2>
          </div>
          <p className="text-xs text-stone-500">
            Tell our styling algorithm which design language resonates most with your taste.
          </p>

          <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 pt-2">
            {styles.map((s) => (
              <button
                key={s}
                type="button"
                onClick={() => setStyle(s)}
                className={`p-4 rounded-xs border text-left transition-all ${
                  style === s
                    ? 'border-[#702C3B] bg-[#702C3B]/5 ring-1 ring-[#702C3B]'
                    : 'border-[#E9E2D8] hover:border-stone-400 bg-white'
                }`}
              >
                <span className="font-serif text-lg font-medium text-stone-900 block">{s}</span>
                <span className="text-[11px] text-stone-500 block mt-1">
                  {s === 'Minimal' && 'Unembellished purity, clean lines, and neutral hues'}
                  {s === 'Classic' && 'Timeless Neapolitan tailoring and heritage codes'}
                  {s === 'Elegant' && 'Bias cuts, fluid drape, and noble natural fibers'}
                  {s === 'Contemporary' && 'Architectural volumes and asymmetrical cuts'}
                  {s === 'Streetwear' && 'Okayama selvedge denim and lugged derby soles'}
                  {s === 'Bold' && 'Expressive geometry, deep wine hues, and contrast'}
                </span>
              </button>
            ))}
          </div>

          <div className="flex items-center justify-between pt-4 border-t border-[#E9E2D8]">
            <button
              onClick={() => setCurrentStep(1)}
              className="px-5 py-2.5 border border-[#E9E2D8] hover:bg-stone-50 text-xs font-mono uppercase tracking-wider rounded-xs flex items-center gap-1.5"
            >
              <ArrowLeft className="w-3.5 h-3.5" />
              <span>Back</span>
            </button>
            <button
              onClick={() => setCurrentStep(3)}
              className="px-6 py-3 bg-[#171717] hover:bg-[#2A2A2A] text-white text-xs font-mono uppercase tracking-widest font-semibold rounded-xs flex items-center gap-2"
            >
              <span>Next: Color Palette</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}

      {/* STEP 3: PREFERRED COLOR PALETTE */}
      {currentStep === 3 && (
        <div className="max-w-3xl mx-auto bg-white border border-[#E9E2D8] p-8 rounded-sm space-y-6 animate-in fade-in duration-200">
          <div className="flex items-center gap-2 text-stone-900 font-serif text-2xl font-medium">
            <Palette className="w-6 h-6 text-[#702C3B]" />
            <h2>Select your chromatic palette</h2>
          </div>
          <p className="text-xs text-stone-500">
            Harmonize top and bottom layers through curated color relationships.
          </p>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 pt-2">
            {palettes.map((p) => (
              <button
                key={p.name}
                type="button"
                onClick={() => setColorPalette(p.name)}
                className={`p-4 rounded-xs border text-left transition-all ${
                  colorPalette === p.name
                    ? 'border-[#702C3B] bg-[#702C3B]/5 ring-1 ring-[#702C3B]'
                    : 'border-[#E9E2D8] hover:border-stone-400 bg-white'
                }`}
              >
                <div className="flex items-center justify-between">
                  <span className="font-serif text-lg font-medium text-stone-900">{p.name}</span>
                  {/* Swatches */}
                  <div className="flex gap-1">
                    {p.name === 'Neutrals' && (
                      <>
                        <span className="w-3 h-3 rounded-full bg-[#F8F6F1] border border-stone-300" />
                        <span className="w-3 h-3 rounded-full bg-[#E9E2D8]" />
                        <span className="w-3 h-3 rounded-full bg-[#B6A99A]" />
                      </>
                    )}
                    {p.name === 'Earth Tones' && (
                      <>
                        <span className="w-3 h-3 rounded-full bg-[#B6A99A]" />
                        <span className="w-3 h-3 rounded-full bg-[#2E7658]" />
                        <span className="w-3 h-3 rounded-full bg-[#702C3B]" />
                      </>
                    )}
                    {p.name === 'Monochrome' && (
                      <>
                        <span className="w-3 h-3 rounded-full bg-[#171717]" />
                        <span className="w-3 h-3 rounded-full bg-[#555555]" />
                        <span className="w-3 h-3 rounded-full bg-[#FFFFFF] border border-stone-300" />
                      </>
                    )}
                    {p.name === 'Jewel Accents' && (
                      <>
                        <span className="w-3 h-3 rounded-full bg-[#702C3B]" />
                        <span className="w-3 h-3 rounded-full bg-[#2E7658]" />
                        <span className="w-3 h-3 rounded-full bg-[#B6A99A]" />
                      </>
                    )}
                  </div>
                </div>
                <p className="text-xs text-stone-500 mt-2">{p.desc}</p>
              </button>
            ))}
          </div>

          <div className="flex items-center justify-between pt-4 border-t border-[#E9E2D8]">
            <button
              onClick={() => setCurrentStep(2)}
              className="px-5 py-2.5 border border-[#E9E2D8] hover:bg-stone-50 text-xs font-mono uppercase tracking-wider rounded-xs flex items-center gap-1.5"
            >
              <ArrowLeft className="w-3.5 h-3.5" />
              <span>Back</span>
            </button>
            <button
              onClick={() => setCurrentStep(4)}
              className="px-6 py-3 bg-[#171717] hover:bg-[#2A2A2A] text-white text-xs font-mono uppercase tracking-widest font-semibold rounded-xs flex items-center gap-2"
            >
              <span>Next: Set Budget</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}

      {/* STEP 4: BUDGET */}
      {currentStep === 4 && (
        <div className="max-w-3xl mx-auto bg-white border border-[#E9E2D8] p-8 rounded-sm space-y-6 animate-in fade-in duration-200">
          <div className="flex items-center gap-2 text-stone-900 font-serif text-2xl font-medium">
            <DollarSign className="w-6 h-6 text-[#702C3B]" />
            <h2>Outfit Budget Allocation</h2>
          </div>
          <p className="text-xs text-stone-500">
            Define your combined wardrobe investment across top, bottom, footwear, and accessory.
          </p>

          <div className="pt-4 space-y-4">
            <div className="flex items-center justify-between">
              <span className="text-xs font-mono uppercase text-stone-600">Total Ensemble Cap</span>
              <span className="font-serif text-2xl font-medium text-[#702C3B]">
                {formatCurrency(budgetMax)}
              </span>
            </div>

            <input
              type="range"
              min="15000"
              max="65000"
              step="2500"
              value={budgetMax}
              onChange={(e) => setBudgetMax(Number(e.target.value))}
              className="w-full accent-[#702C3B] cursor-pointer"
            />

            <div className="flex justify-between text-xs font-mono text-stone-400">
              <span>₹15,000 (Essential edit)</span>
              <span>₹35,000 (Curated luxury)</span>
              <span>₹65,000+ (Atelier grand)</span>
            </div>
          </div>

          <div className="flex items-center justify-between pt-4 border-t border-[#E9E2D8]">
            <button
              onClick={() => setCurrentStep(3)}
              className="px-5 py-2.5 border border-[#E9E2D8] hover:bg-stone-50 text-xs font-mono uppercase tracking-wider rounded-xs flex items-center gap-1.5"
            >
              <ArrowLeft className="w-3.5 h-3.5" />
              <span>Back</span>
            </button>
            <button
              onClick={() => setCurrentStep(5)}
              className="px-6 py-3 bg-[#171717] hover:bg-[#2A2A2A] text-white text-xs font-mono uppercase tracking-widest font-semibold rounded-xs flex items-center gap-2"
            >
              <span>Next: Fit &amp; Tailoring</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}

      {/* STEP 5: FIT & GENDER PREFERENCES */}
      {currentStep === 5 && (
        <div className="max-w-3xl mx-auto bg-white border border-[#E9E2D8] p-8 rounded-sm space-y-6 animate-in fade-in duration-200">
          <div className="flex items-center gap-2 text-stone-900 font-serif text-2xl font-medium">
            <Layers className="w-6 h-6 text-[#702C3B]" />
            <h2>Atelier Department &amp; Fit Profile</h2>
          </div>
          <p className="text-xs text-stone-500">
            Fine-tune the silhouette drape and wardrobe department.
          </p>

          <div className="space-y-4 pt-2">
            <div>
              <label className="block text-xs font-mono uppercase text-stone-600 mb-2">
                Wardrobe Department
              </label>
              <div className="grid grid-cols-2 gap-3">
                {(['Women', 'Men'] as const).map((cat) => (
                  <button
                    key={cat}
                    type="button"
                    onClick={() => setGenderCategory(cat)}
                    className={`py-3 px-4 rounded-xs border text-center font-serif text-base transition-all ${
                      genderCategory === cat
                        ? 'border-[#702C3B] bg-[#702C3B] text-white'
                        : 'border-[#E9E2D8] bg-white text-stone-800 hover:border-stone-400'
                    }`}
                  >
                    {cat}’s Atelier
                  </button>
                ))}
              </div>
            </div>

            <div>
              <label className="block text-xs font-mono uppercase text-stone-600 mb-2">
                Silhouette Drape Preference
              </label>
              <div className="grid grid-cols-3 gap-3">
                {(['Slim', 'Regular', 'Relaxed'] as const).map((f) => (
                  <button
                    key={f}
                    type="button"
                    onClick={() => setFit(f)}
                    className={`py-3 px-4 rounded-xs border text-center text-xs font-medium transition-all ${
                      fit === f
                        ? 'border-[#171717] bg-[#171717] text-white'
                        : 'border-[#E9E2D8] bg-white text-stone-800 hover:border-stone-400'
                    }`}
                  >
                    {f} Fit
                  </button>
                ))}
              </div>
            </div>
          </div>

          <div className="flex items-center justify-between pt-6 border-t border-[#E9E2D8]">
            <button
              onClick={() => setCurrentStep(4)}
              className="px-5 py-2.5 border border-[#E9E2D8] hover:bg-stone-50 text-xs font-mono uppercase tracking-wider rounded-xs flex items-center gap-1.5"
            >
              <ArrowLeft className="w-3.5 h-3.5" />
              <span>Back</span>
            </button>
            <button
              onClick={handleGenerateOutfit}
              className="px-8 py-3 bg-[#702C3B] hover:bg-[#5A232F] text-white text-xs font-mono uppercase tracking-widest font-semibold rounded-xs shadow-md flex items-center gap-2"
            >
              <Sparkles className="w-4 h-4" />
              <span>Synthesize My Look</span>
            </button>
          </div>
        </div>
      )}

      {/* STEP 6: GENERATED LOOK PRESENTATION SCREEN */}
      {currentStep === 6 && generatedLook && (
        <div className="space-y-8 animate-in fade-in duration-300">
          {/* Top Banner / Match Summary */}
          <div className="bg-white border border-[#E9E2D8] p-6 sm:p-8 rounded-sm flex flex-col md:flex-row md:items-center justify-between gap-6">
            <div className="space-y-2">
              <div className="flex items-center gap-2">
                <span className="text-[10px] uppercase font-mono tracking-widest px-2.5 py-0.5 bg-[#2E7658]/10 text-[#2E7658] font-semibold rounded">
                  {generatedLook.matchScore}% Match Index
                </span>
                <span className="text-xs text-stone-400">•</span>
                <span className="text-xs font-mono text-stone-600">
                  {occasion} • {style} • {colorPalette}
                </span>
              </div>
              <h2 className="font-serif text-3xl font-medium text-stone-900">
                The {occasion} {style} Ensemble
              </h2>
              <p className="text-xs text-stone-600 max-w-2xl leading-relaxed">
                {generatedLook.explanation}
              </p>
            </div>

            <div className="text-left md:text-right shrink-0">
              <span className="text-[10px] uppercase font-mono tracking-widest text-stone-400 block">
                Total Wardrobe Value
              </span>
              <span className="font-serif text-3xl font-medium text-stone-900">
                {formatCurrency(totalLookPrice)}
              </span>
              <span className="text-[11px] text-stone-500 block mt-0.5">
                4 Atelier Coordinating Pieces
              </span>
            </div>
          </div>

          {/* 4-Item Grid */}
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-6">
            {([
              { key: 'top', label: 'Layer / Top', item: generatedLook.top },
              { key: 'bottom', label: 'Trousers / Bottom', item: generatedLook.bottom },
              { key: 'shoes', label: 'Handcrafted Footwear', item: generatedLook.shoes },
              { key: 'accessory', label: 'Accents & Accoutrements', item: generatedLook.accessory },
            ] as const).map(({ key, label, item }) => (
              <div
                key={key}
                className="bg-white border border-[#E9E2D8] rounded-sm overflow-hidden flex flex-col justify-between"
              >
                <div className="relative aspect-3/4 bg-stone-100 overflow-hidden group">
                  <Image
                    src={item.images[0]}
                    alt={item.name}
                    fill
                    sizes="(max-width: 640px) 100vw, 25vw"
                    className="object-cover group-hover:scale-105 transition-transform duration-500"
                  />
                  <div className="absolute top-2.5 left-2.5 bg-white/90 backdrop-blur-xs text-stone-800 text-[10px] font-mono uppercase tracking-wider px-2 py-0.5 rounded-xs">
                    {label}
                  </div>
                </div>

                <div className="p-4 flex flex-col flex-1 justify-between">
                  <div>
                    <span className="text-[10px] font-mono uppercase tracking-wider text-stone-400">
                      {item.brand}
                    </span>
                    <Link
                      href={`/product/${item.slug}`}
                      className="font-serif text-base font-medium text-stone-900 block hover:text-[#702C3B] line-clamp-1 mt-0.5"
                    >
                      {item.name}
                    </Link>
                    <p className="text-[11px] text-stone-500 mt-1 line-clamp-1">{item.material}</p>
                  </div>

                  <div className="mt-4 pt-3 border-t border-[#E9E2D8] flex items-center justify-between">
                    <span className="font-medium text-stone-900 text-sm">
                      {formatCurrency(item.price)}
                    </span>
                    <button
                      onClick={() => setReplacingSlot(key)}
                      className="text-[11px] font-mono uppercase text-[#702C3B] hover:underline flex items-center gap-1"
                    >
                      <RefreshCw className="w-3 h-3" />
                      <span>Replace</span>
                    </button>
                  </div>
                </div>
              </div>
            ))}
          </div>

          {/* Action Bar (Save Outfit, Add All to Cart, Restart) */}
          <div className="p-6 bg-white border border-[#E9E2D8] rounded-sm flex flex-col sm:flex-row items-center justify-between gap-4">
            <button
              onClick={() => setCurrentStep(1)}
              className="text-xs font-mono uppercase tracking-wider text-stone-600 hover:text-black flex items-center gap-1.5"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>Restart Styling Wizard</span>
            </button>

            <div className="flex items-center gap-3 w-full sm:w-auto">
              <button
                onClick={handleSaveOutfit}
                disabled={savedSuccess}
                className="flex-1 sm:flex-none px-6 py-3 border border-[#171717] hover:bg-[#171717] hover:text-white text-stone-900 text-xs font-mono uppercase tracking-widest font-semibold rounded-xs transition-colors flex items-center justify-center gap-2"
              >
                {savedSuccess ? (
                  <>
                    <Check className="w-4 h-4 text-emerald-600" />
                    <span>Saved to Wardrobe</span>
                  </>
                ) : (
                  <>
                    <Bookmark className="w-4 h-4" />
                    <span>Save This Look</span>
                  </>
                )}
              </button>

              <button
                onClick={handleAddAllToCart}
                disabled={addedAllSuccess}
                className="flex-1 sm:flex-none px-8 py-3 bg-[#702C3B] hover:bg-[#5A232F] text-white text-xs font-mono uppercase tracking-widest font-semibold rounded-xs shadow-md transition-colors flex items-center justify-center gap-2"
              >
                {addedAllSuccess ? (
                  <>
                    <Check className="w-4 h-4 text-emerald-400" />
                    <span>Added All 4 Items</span>
                  </>
                ) : (
                  <>
                    <ShoppingBag className="w-4 h-4" />
                    <span>Add Complete Look to Bag</span>
                  </>
                )}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Replacement Modal Selector */}
      {replacingSlot && generatedLook && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-xs animate-in fade-in duration-150">
          <div className="fixed inset-0" onClick={() => setReplacingSlot(null)} />
          <div className="relative bg-[#F8F6F1] border border-[#E9E2D8] rounded-sm max-w-3xl w-full max-h-[85vh] overflow-y-auto p-6 z-10 shadow-2xl">
            <div className="flex items-center justify-between pb-4 border-b border-[#E9E2D8]">
              <div>
                <h3 className="font-serif text-xl font-medium text-stone-900">
                  Select Alternative {replacingSlot.toUpperCase()}
                </h3>
                <p className="text-xs text-stone-500">
                  Choose another piece from the VELORA collection to substitute in your outfit.
                </p>
              </div>
              <button
                onClick={() => setReplacingSlot(null)}
                className="text-stone-500 hover:text-black text-xs font-mono uppercase"
              >
                Close
              </button>
            </div>

            <div className="grid grid-cols-2 sm:grid-cols-3 gap-4 pt-6">
              {products
                .filter((p) => {
                  if (replacingSlot === 'shoes') return p.category === 'Footwear';
                  if (replacingSlot === 'accessory') return p.category === 'Accessories';
                  if (replacingSlot === 'bottom')
                    return ['Trousers', 'Skirts'].includes(p.subcategory);
                  return ['Blazers', 'Tops', 'Knitwear', 'Outerwear', 'Shirts', 'Dresses'].includes(
                    p.subcategory
                  );
                })
                .slice(0, 9)
                .map((candidate) => (
                  <div
                    key={candidate.id}
                    onClick={() => handleReplaceItem(replacingSlot, candidate)}
                    className="p-3 bg-white border border-[#E9E2D8] hover:border-[#702C3B] rounded-xs cursor-pointer transition-all flex flex-col justify-between"
                  >
                    <div className="relative aspect-3/4 rounded-xs overflow-hidden bg-stone-100">
                      <Image
                        src={candidate.images[0]}
                        alt={candidate.name}
                        fill
                        sizes="200px"
                        className="object-cover"
                      />
                    </div>
                    <div className="mt-2">
                      <span className="text-[10px] font-mono uppercase text-stone-400 block">
                        {candidate.brand}
                      </span>
                      <h4 className="text-xs font-medium text-stone-900 line-clamp-1">
                        {candidate.name}
                      </h4>
                      <span className="text-xs font-semibold text-[#702C3B] mt-1 block">
                        {formatCurrency(candidate.price)}
                      </span>
                    </div>
                  </div>
                ))}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
